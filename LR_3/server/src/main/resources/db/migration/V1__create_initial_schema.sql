CREATE TABLE students (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    isu INTEGER NOT NULL,
    fio VARCHAR(150) NOT NULL,
    student_group VARCHAR(10) NOT NULL,
    dorm INTEGER,
    room INTEGER,
    settlement_date DATE,
    is_foreigner BOOLEAN NOT NULL DEFAULT FALSE,
    notes VARCHAR(500) NOT NULL DEFAULT '',
    CONSTRAINT uq_students_isu UNIQUE (isu),
    CONSTRAINT ck_students_isu CHECK (isu BETWEEN 100000 AND 999999),
    CONSTRAINT ck_students_fio CHECK (length(trim(fio)) > 0),
    CONSTRAINT ck_students_group CHECK (student_group ~ '^[A-Z][0-9]{4}$'),
    CONSTRAINT ck_students_dorm CHECK (dorm BETWEEN 1 AND 999),
    CONSTRAINT ck_students_room CHECK (room BETWEEN 1 AND 9999),
    CONSTRAINT ck_students_date CHECK (settlement_date >= DATE '2000-01-01'),
    CONSTRAINT ck_students_settlement CHECK (
        (dorm IS NULL AND room IS NULL AND settlement_date IS NULL)
        OR (dorm IS NOT NULL AND room IS NOT NULL AND settlement_date IS NOT NULL)
    )
);

CREATE INDEX ix_students_group ON students (student_group);
CREATE INDEX ix_students_settlement ON students (dorm, room);
CREATE INDEX ix_students_fio ON students (fio, isu);

CREATE TABLE app_users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR(64) NOT NULL,
    email VARCHAR(254) NOT NULL,
    password_hash VARCHAR(255) NOT NULL,
    role VARCHAR(16) NOT NULL DEFAULT 'USER',
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_users_username CHECK (length(trim(username)) > 0),
    CONSTRAINT ck_users_email CHECK (length(trim(email)) > 0),
    CONSTRAINT ck_users_password_hash CHECK (length(trim(password_hash)) > 0),
    CONSTRAINT ck_users_role CHECK (role IN ('ADMIN', 'USER'))
);

CREATE UNIQUE INDEX uq_users_username ON app_users (lower(username));
CREATE UNIQUE INDEX uq_users_email ON app_users (lower(email));

CREATE TABLE refresh_tokens (
    id UUID PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES app_users (id) ON DELETE CASCADE,
    token_hash VARCHAR(64) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    expires_at TIMESTAMP WITH TIME ZONE NOT NULL,
    revoked_at TIMESTAMP WITH TIME ZONE,
    CONSTRAINT uq_refresh_tokens_hash UNIQUE (token_hash),
    CONSTRAINT ck_refresh_tokens_hash CHECK (token_hash ~ '^[0-9a-f]{64}$'),
    CONSTRAINT ck_refresh_tokens_expiry CHECK (expires_at > created_at),
    CONSTRAINT ck_refresh_tokens_revocation CHECK (revoked_at IS NULL OR revoked_at >= created_at)
);

CREATE INDEX ix_refresh_tokens_user ON refresh_tokens (user_id);
CREATE INDEX ix_refresh_tokens_expiry ON refresh_tokens (expires_at);
